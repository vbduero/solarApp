import 'package:flutter/material.dart';
import '../models/task_model.dart';
import '../services/api_service.dart';
import '../config/api_constants.dart';

/// Provider que gestiona las tareas de cuidado de plantas
class TaskProvider extends ChangeNotifier {
  List<TaskModel> _todayTasks = [];
  List<TaskModel> _upcomingTasks = [];
  bool _isLoading = false;
  int _todayRequestId = 0;
  int _upcomingRequestId = 0;

  List<TaskModel> get todayTasks => _todayTasks;
  List<TaskModel> get upcomingTasks => _upcomingTasks;
  bool get isLoading => _isLoading;

  /// Hay tareas de ejemplo en Hoy (modo demo). Se calcula sobre `todayTasks`.
  bool get showingDemoTasks => todayTasks.any((t) => t.isDemo);

  /// Limpia todo el estado al cerrar sesión e invalida las peticiones en vuelo.
  void clearSession() {
    _todayRequestId++;
    _upcomingRequestId++;
    _todayTasks = [];
    _upcomingTasks = [];
    _isLoading = false;
    notifyListeners();
  }

  /// Cantidad total de tareas pendientes
  int get pendingCount => _todayTasks.where((t) => !t.isCompleted).length;

  /// Tareas agrupadas por tipo
  Map<String, List<TaskModel>> get tasksByType {
    final map = <String, List<TaskModel>>{};
    for (final task in _todayTasks) {
      map.putIfAbsent(task.taskType, () => []);
      map[task.taskType]!.add(task);
    }
    return map;
  }

  /// Cargar tareas de hoy
  Future<void> loadTodayTasks() async {
    final requestId = ++_todayRequestId;
    _isLoading = true;
    notifyListeners();

    try {
      final data = await ApiService.get(
        ApiConstants.tasks,
        queryParams: {'upcoming': 'false'},
      );
      if (requestId != _todayRequestId) return;
      _todayTasks = (data as List).map((t) => TaskModel.fromJson(t)).toList();
    } catch (e) {
      if (requestId != _todayRequestId) return;
      _loadDemoTasks();
    }

    _isLoading = false;
    notifyListeners();
  }

  /// Cargar tareas próximas
  Future<void> loadUpcomingTasks() async {
    final requestId = ++_upcomingRequestId;
    try {
      final data = await ApiService.get(
        ApiConstants.tasks,
        queryParams: {'upcoming': 'true'},
      );
      if (requestId != _upcomingRequestId) return;
      _upcomingTasks = (data as List)
          .map((t) => TaskModel.fromJson(t))
          .toList();
    } catch (e) {
      if (requestId != _upcomingRequestId) return;
      // Sin datos demo para próximas
    }
    notifyListeners();
  }

  /// Crear una tarea y ubicarla en Hoy o Próximamente según su fecha
  Future<bool> createTask({
    required int plantId,
    required String taskType,
    required DateTime dueDate,
    String? description,
  }) async {
    _isLoading = true;
    notifyListeners();

    try {
      final data = await ApiService.post(
        ApiConstants.tasks,
        body: {
          'plant_id': plantId,
          'task_type': taskType,
          'due_date': dueDate.toUtc().toIso8601String(),
          if (description != null && description.trim().isNotEmpty)
            'description': description.trim(),
        },
      );
      final task = TaskModel.fromJson(data);

      // Misma regla del backend: solo lo posterior a ahora es "Próximamente"
      if (task.dueDate.isAfter(DateTime.now())) {
        _upcomingTasks = _sortedByDueDate([..._upcomingTasks, task]);
      } else {
        _todayTasks = _sortedByDueDate([..._todayTasks, task]);
      }
      return true;
    } catch (e) {
      debugPrint('Error al crear la tarea: $e');
      return false;
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  /// Completar una tarea
  Future<bool> completeTask(int taskId) async {
    try {
      final data = await ApiService.patch(
        '${ApiConstants.tasks}$taskId',
        body: {'status': 'Completada'},
      );
      final updated = TaskModel.fromJson(data);

      // La tarea puede estar en cualquiera de las dos listas
      TaskModel replace(TaskModel t) => t.id == taskId ? updated : t;
      _todayTasks = _todayTasks.map(replace).toList();
      _upcomingTasks = _upcomingTasks.map(replace).toList();
      notifyListeners();
      return true;
    } catch (e) {
      debugPrint('Error al completar la tarea: $e');
      return false;
    }
  }

  /// Ordena por fecha de vencimiento, igual que el GET del backend
  List<TaskModel> _sortedByDueDate(List<TaskModel> tasks) {
    return tasks..sort((a, b) => a.dueDate.compareTo(b.dueDate));
  }

  /// Datos de demo
